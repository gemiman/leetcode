use std::collections::HashMap;

/// 1. 两数之和
/// 给定一个整数数组 nums 和一个整数目标值 target，请你在该数组中找出 和为目标值 target  的那 两个 整数，并返回它们的数组下标。
/// 你可以假设每种输入只会对应一个答案，并且你不能使用两次相同的元素。
///
/// 你可以按任意顺序返回答案。

/// 1. 暴力法
/// 穷举数组中所有两数组合，找出和等于 `target` 的两个下标并返回。
///
/// # 参数
/// - `nums`：整数数组，按值传入（函数取得所有权，内部只读、不修改）
/// - `target`：目标值
///
/// # 返回值
/// `Vec<i32>`：长度为 2 的下标数组 `[i, j]`，满足 `nums[i] + nums[j] == target`
///
/// # 复杂度
/// - 时间复杂度 O(n²)：两层嵌套循环共检查 n² 个元素对
/// - 空间复杂度 O(1)：除返回值外不占用与 n 相关的额外空间
///
/// # Panics
/// 题目保证每组输入恰有一个答案；若遍历结束仍未找到，则直接 panic。
///
/// # 已知缺陷
/// 内层循环从下标 0 开始且未跳过 `i == j`，当某元素满足 `num + num == target`
/// 时会返回两个相同下标，违反"不能使用两次相同元素"的约束；
/// 严谨写法应让内层从 `i + 1` 开始遍历（同时避免重复检查对称的元素对）。
pub fn two_sum_brute_force(nums: Vec<i32>, target: i32) -> Vec<i32> {
    // enumerate() 把迭代器元素包装成 (下标, 元素引用) 元组；
    // 模式中的 &num 会解引用 &i32，把值拷贝成 i32，便于直接做加法。
    for (i, &num) in nums.iter().enumerate() {
        // 内层再次从头遍历整个数组，让 num 与每一个 num2 配对，共 n² 对。
        for (j, &num2) in nums.iter().enumerate() {
            // 判断当前这一对元素的和是否等于目标值。
            if num + num2 == target {
                // return 提前结束整个函数，两层循环一并终止；
                // vec! 宏构造 Vec<i32> 作为返回值；
                // i、j 的类型是 usize，Rust 不做隐式数值转换，需 as i32 显式转成返回类型。
                return vec![i as i32, j as i32];
            }
        }
    }
    // 题目保证必有解，正常执行不会走到这里；
    // 若确实没找到，用 panic 报错而不是返回空 Vec，避免调用方拿到无意义的假结果。
    panic!("No solution")
}

/// 2. 哈希表
/// 一趟遍历 + 哈希表求两数之和：把"找两数之和"转化为"查补数是否出现过"。
///
/// # 思路
/// 对当前元素 `num`，令补数 `complement = target - num`；
/// 若表中已存有 `complement`，说明它与当前元素构成答案，直接返回两者下标；
/// 否则把 `num -> 下标` 存入表中，供后续元素查询。表中只保存"已经走过的"元素，
/// 因此天然不会重复使用同一个元素。
///
/// # 参数
/// - `nums`：整数数组，按值传入（函数取得所有权，内部只读、不修改）
/// - `target`：目标值
///
/// # 返回值
/// `Vec<i32>`：长度为 2 的下标数组 `[j, i]`，其中 j 是之前保存的下标、i 是当前下标
///
/// # 复杂度
/// - 时间复杂度 O(n) 均摊：只遍历一趟，每次 HashMap 查找/插入均摊 O(1)
/// - 空间复杂度 O(n)：最坏情况下表中需存放 n 个元素
///
/// # Panics
/// 题目保证每组输入恰有一个答案；若遍历结束仍未找到，则直接 panic。
///
/// # 注意
/// 必须"先查后插"：若先插入再查，遇到 `target == num + num` 时会把当前元素自己
/// 当成补数，返回 `[i, i]`，违反"不能使用两次相同的元素"。
/// 另外 `target - num` 在极端取值下可能 i32 溢出（debug 模式会 panic），
/// 数据范围更大时可改用 i64 计算。
pub fn two_sum_hash(nums: Vec<i32>, target: i32) -> Vec<i32> {
    // 键为元素值 i32，值为其下标 i32；具体泛型类型由下面 get/insert 的用法推断。
    // 必须 mut：遍历过程中要不断 insert。
    let mut map = HashMap::new();
    // 一趟遍历：i 是下标（usize），&num 把 &i32 解引用拷贝成 i32。
    for (i, &num) in nums.iter().enumerate() {
        // get 需要的键类型是 &i32，故对临时算出的补数取引用 &(target - num)；
        // 返回 Option<&i32>：Some(j) 表示补数在之前的元素中出现过，j 是下标引用。
        if let Some(j) = map.get(&(target - num)) {
            // *j 解引用取出之前保存的下标；i as i32 把 usize 显式转成 i32。
            // 顺序是 [旧下标, 当前下标]，题目允许按任意顺序返回。
            return vec![*j, i as i32];
        }
        // 未命中才把当前元素登记进表，供后面的元素配对；
        // 数值重复时新下标会覆盖旧下标，但本题保证答案唯一，不影响结果。
        map.insert(num, i as i32);
    }
    // 题目保证必有解，正常执行不会走到这里；
    // 若确实没找到则 panic，而不是返回空 Vec 造成"假答案"。
    panic!("No solution")
}

#[test]
fn test_two_sum_hash() {
    assert_eq!(two_sum_hash(vec![2, 7, 11, 15], 9), vec![0, 1]);
}
